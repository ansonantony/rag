"""AI-assisted evaluation dataset generation from source document chunks."""

import json
from pathlib import Path
from typing import Any

from huggingface_hub import InferenceClient
from app.core.config import get_settings
from app.evaluation.dataset import EvalRecord, validate_eval_records

GENERATION_SYSTEM_PROMPT = (
    "You are an instructional-design assistant that creates question-answer evaluation "
    "cases from source material for a retrieval-augmented generation (RAG) benchmark. "
    "Only create questions whose answers are supported by the provided source context. "
    "For every candidate, provide a concise reference answer and an evidence quote or "
    "chunk reference. Never invent facts."
)

GENERATION_USER_PROMPT_TEMPLATE = """Source context:
{context}

Generate up to {max_candidates} candidate evaluation questions with reference answers grounded in the source context.
Return ONLY a JSON object with an "candidates" array. Each candidate must include:
- question: the user-facing question
- reference_answer: concise supported answer
- evidence_quote: short quote supporting the answer
- relevant_chunk_ids: list of chunk identifiers used as evidence
- question_type: one of fact_lookup, multi_chunk, synthesis, ambiguous, unanswerable
- answerable: true when supported, false when not supported by the source
- source_document_ids: list of source document identifiers

JSON shape:
{{"candidates": [{{"question": "...", "reference_answer": "...", "evidence_quote": "...", "relevant_chunk_ids": ["..."], "question_type": "...", "answerable": true, "source_document_ids": ["..."]}}]}}
"""


def format_context(chunks: list[Any], max_chars: int = 6000) -> str:
    """Format source chunks into a bounded context string for generation."""
    parts: list[str] = []
    used = 0
    for chunk in chunks or []:
        text = getattr(chunk, "page_content", "") or ""
        metadata = getattr(chunk, "metadata", None) or {}
        chunk_id = metadata.get("chunk_id") or metadata.get("source_chunk_id") or "unknown"
        page = metadata.get("page_label") or metadata.get("page") or "unknown"
        part = f"[Chunk {chunk_id} | page {page}]\n{text}"
        if used + len(part) > max_chars:
            break
        parts.append(part)
        used += len(part) + 2
    return "\n\n".join(parts)


def generate_candidate_records(chunks: list[Any], client: InferenceClient, max_candidates: int = 30, model: str | None = None) -> list[dict[str, Any]]:
    """Generate candidate QA records from source chunks using the configured HF chat model."""
    context = format_context(chunks)
    if not context.strip():
        return []
    settings = get_settings()
    response = client.chat_completion(
        model=model or settings.hf_chat_model,
        messages=[
            {"role": "system", "content": GENERATION_SYSTEM_PROMPT},
            {"role": "user", "content": GENERATION_USER_PROMPT_TEMPLATE.format(context=context, max_candidates=max_candidates)},
        ],
        max_tokens=4096,
    )
    content = (response.choices[0].message.content or "").strip()
    payload: dict[str, Any] = {}
    try:
        payload = json.loads(content)
    except json.JSONDecodeError:
        start = content.find("{")
        end = content.rfind("}")
        if start != -1 and end != -1:
            payload = json.loads(content[start : end + 1])
    candidates = payload.get("candidates") if isinstance(payload, dict) else None
    if not isinstance(candidates, list):
        candidates = []
    records: list[dict[str, Any]] = []
    for candidate in candidates:
        if not isinstance(candidate, dict):
            continue
        records.append(
            {
                "id": f"rag-eval-{len(records) + 1:04d}",
                "question": str(candidate.get("question") or ""),
                "reference_answer": str(candidate.get("reference_answer") or "") or None,
                "source_document_ids": [str(doc_id) for doc_id in candidate.get("source_document_ids") or ["sample"]],
                "relevant_chunk_ids": [str(cid) for cid in candidate.get("relevant_chunk_ids") or []],
                "answerable": bool(candidate.get("answerable", True)),
                "question_type": str(candidate.get("question_type") or "fact_lookup"),
                "generation_method": "llm_assisted",
                "validation_status": "pending",
                "evidence_quote": str(candidate.get("evidence_quote") or "") or None,
                "review_notes": "Generated by AI-assisted evaluation dataset generation; pending human review.",
            }
        )
    return records


def write_jsonl_records(records: list[dict[str, Any]], path: str | Path) -> Path:
    """Write evaluation records as JSONL."""
    file_path = Path(path)
    file_path.parent.mkdir(parents=True, exist_ok=True)
    with file_path.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record) + "\n")
    return file_path


def run_candidate_generation(chunks: list[Any], client: InferenceClient, max_candidates: int = 30) -> tuple[list[EvalRecord], list[str]]:
    """Generate and validate candidate records; returns (valid_records, errors)."""
    raw_records = generate_candidate_records(chunks, client, max_candidates=max_candidates)
    valid, errors = validate_eval_records(raw_records)
    return valid, errors
